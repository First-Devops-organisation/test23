<#
.SYNOPSIS
    Decrypts secrets in a migrated GitHub repo that were encrypted during ADO migration.
.DESCRIPTION
    After a repo is migrated from Azure DevOps to GitHub, this script finds all
    ENC{<base64>} tokens in the working tree, decrypts them using the shared
    passphrase, writes the restored files, and optionally commits + pushes the result.

    Reads the secret-manifest.json (generated by scrub-secrets.ps1 -Mode encrypt)
    to know which files contained secrets. Also performs a full-tree scan for any
    ENC{} tokens not in the manifest.

    IMPORTANT: Run this AFTER migration, BEFORE teams start using the GitHub repo.
.PARAMETER RepoDir
    Path to the cloned GitHub repo (already checked out).
.PARAMETER Passphrase
    The same passphrase used during encryption in scrub-secrets.ps1.
.PARAMETER DryRun
    If set, reports what would be decrypted without modifying any files.
.PARAMETER CommitChanges
    If set, commits and pushes decrypted changes to the repo.
.PARAMETER RemoveManifest
    If set, removes secret-manifest.json after successful decryption.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$RepoDir,

    [Parameter(Mandatory = $true)]
    [string]$Passphrase,

    [switch]$DryRun,
    [switch]$CommitChanges,
    [switch]$RemoveManifest
)

$ErrorActionPreference = "Stop"

# --- Import crypto module ---
$cryptoModulePath = Join-Path $PSScriptRoot "..\01-prep\secrets-crypto.psm1"
if (-not (Test-Path $cryptoModulePath)) {
    # Try relative to repo root (when run from GitHub Actions)
    $cryptoModulePath = Join-Path $PSScriptRoot "..\..\migration-accelerator\01-prep\secrets-crypto.psm1"
}
if (-not (Test-Path $cryptoModulePath)) {
    Write-Error "Cannot find secrets-crypto.psm1. Searched: $cryptoModulePath"
    exit 1
}
Import-Module $cryptoModulePath -Force

# --- Validate repo directory ---
if (-not (Test-Path $RepoDir)) {
    Write-Error "Repository directory not found: $RepoDir"
    exit 1
}

Write-Host "=== Secret Decryption $(if ($DryRun) {'(DRY RUN)'} else {'(LIVE)'}) ===" -ForegroundColor Cyan
Write-Host "Repo: $RepoDir" -ForegroundColor Gray

# --- Load manifest if present ---
$manifestFile = Join-Path $RepoDir "secret-manifest.json"
$manifest = $null
$manifestEntries = @()

if (Test-Path $manifestFile) {
    Write-Host "Found secret-manifest.json — using manifest-guided decryption" -ForegroundColor Green
    $manifest = Get-Content $manifestFile -Raw | ConvertFrom-Json
    $manifestEntries = $manifest.secrets
    Write-Host "  Manifest contains $($manifestEntries.Count) encrypted secret entries" -ForegroundColor Gray
}
else {
    Write-Host "No secret-manifest.json found — falling back to full-tree scan" -ForegroundColor Yellow
}

# --- Get the ENC{} regex pattern ---
$encPattern = Get-EncryptedPattern

# --- Scan files for ENC{} tokens ---
$filesToProcess = @()

if ($manifestEntries.Count -gt 0) {
    # Use manifest for targeted file list
    $uniqueFiles = $manifestEntries | Select-Object -ExpandProperty File -Unique
    foreach ($relPath in $uniqueFiles) {
        $fullPath = Join-Path $RepoDir $relPath
        if (Test-Path $fullPath) {
            $filesToProcess += $fullPath
        }
        else {
            Write-Warning "Manifest file not found in repo: $relPath"
        }
    }
}

# Also do a full-tree scan to catch any ENC{} tokens not in the manifest
Write-Host "Scanning repository for ENC{} tokens..." -ForegroundColor Gray
$allFiles = Get-ChildItem -Path $RepoDir -Recurse -File |
    Where-Object {
        $_.FullName -notmatch '[\\/]\.git[\\/]' -and
        $_.FullName -notmatch '[\\/]node_modules[\\/]' -and
        $_.FullName -notmatch '[\\/]\.vs[\\/]' -and
        $_.Extension -notin @('.exe', '.dll', '.zip', '.tar', '.gz', '.png', '.jpg', '.gif', '.ico', '.woff', '.woff2', '.ttf', '.eot') -and
        $_.Name -ne 'secret-manifest.json'
    }

foreach ($file in $allFiles) {
    if ($filesToProcess -notcontains $file.FullName) {
        try {
            $content = Get-Content $file.FullName -Raw -ErrorAction SilentlyContinue
            if ($content -and $content -match $encPattern) {
                $filesToProcess += $file.FullName
            }
        }
        catch {
            # Skip binary/unreadable files
        }
    }
}

$filesToProcess = $filesToProcess | Select-Object -Unique

if ($filesToProcess.Count -eq 0) {
    Write-Host "`nNo encrypted secrets found in repository." -ForegroundColor Green
    exit 0
}

Write-Host "Found $($filesToProcess.Count) file(s) with encrypted secrets" -ForegroundColor Yellow

# --- Decrypt ---
$totalDecrypted = 0
$totalFailed = 0
$decryptionLog = @()

foreach ($filePath in $filesToProcess) {
    $relPath = $filePath.Replace($RepoDir, "").TrimStart("\", "/")
    Write-Host "`n  Processing: $relPath" -ForegroundColor Yellow

    try {
        $content = Get-Content $filePath -Raw
        $matches_found = [regex]::Matches($content, $encPattern)

        if ($matches_found.Count -eq 0) {
            Write-Host "    No ENC{} tokens found (already decrypted?)" -ForegroundColor Gray
            continue
        }

        Write-Host "    Found $($matches_found.Count) encrypted token(s)" -ForegroundColor Gray

        $newContent = $content
        $fileDecrypted = 0
        $fileFailed = 0

        # Process matches in reverse order to preserve string positions
        $sortedMatches = $matches_found | Sort-Object { $_.Index } -Descending

        foreach ($match in $sortedMatches) {
            $encryptedToken = $match.Value

            try {
                $decryptedValue = Unprotect-Secret -EncryptedValue $encryptedToken -Passphrase $Passphrase

                if ($DryRun) {
                    $maskedOriginal = $decryptedValue.Substring(0, [Math]::Min(4, $decryptedValue.Length)) + "****"
                    Write-Host "    [DRY RUN] Would decrypt: $($encryptedToken.Substring(0, [Math]::Min(20, $encryptedToken.Length)))... → $maskedOriginal" -ForegroundColor Gray
                }
                else {
                    $newContent = $newContent.Substring(0, $match.Index) + $decryptedValue + $newContent.Substring($match.Index + $match.Length)
                }

                $fileDecrypted++
                $totalDecrypted++

                $decryptionLog += [PSCustomObject]@{
                    File       = $relPath
                    Status     = "DECRYPTED"
                    TokenStart = $match.Index
                    Length     = $decryptedValue.Length
                }
            }
            catch {
                Write-Warning "    Failed to decrypt token at position $($match.Index): $_"
                $fileFailed++
                $totalFailed++

                $decryptionLog += [PSCustomObject]@{
                    File       = $relPath
                    Status     = "FAILED"
                    TokenStart = $match.Index
                    Length     = 0
                    Error      = $_.ToString()
                }
            }
        }

        if (-not $DryRun -and $fileDecrypted -gt 0) {
            # Write restored content — preserve original encoding
            [System.IO.File]::WriteAllText($filePath, $newContent, [System.Text.Encoding]::UTF8)
            Write-Host "    ✓ Restored $fileDecrypted secret(s)" -ForegroundColor Green
        }
        elseif ($DryRun) {
            Write-Host "    [DRY RUN] Would restore $fileDecrypted secret(s)" -ForegroundColor Gray
        }

        if ($fileFailed -gt 0) {
            Write-Host "    ✗ Failed to decrypt $fileFailed token(s)" -ForegroundColor Red
        }
    }
    catch {
        Write-Warning "  Error processing $relPath : $_"
        $decryptionLog += [PSCustomObject]@{
            File   = $relPath
            Status = "ERROR"
            Error  = $_.ToString()
        }
    }
}

# --- Remove manifest ---
if (-not $DryRun -and $RemoveManifest -and (Test-Path $manifestFile) -and $totalFailed -eq 0) {
    Remove-Item $manifestFile -Force
    Write-Host "`nRemoved secret-manifest.json" -ForegroundColor Gray
}

# --- Commit changes ---
if (-not $DryRun -and $CommitChanges -and $totalDecrypted -gt 0) {
    Write-Host "`nCommitting decrypted changes..." -ForegroundColor Yellow
    Push-Location $RepoDir
    try {
        git add -A 2>&1 | Out-Null
        git commit -m "chore: decrypt secrets after ADO-to-GitHub migration`n`nDecrypted $totalDecrypted secret(s) across $($filesToProcess.Count) file(s).`nGenerated by decrypt-secrets.ps1" 2>&1
        git push 2>&1
        Write-Host "  ✓ Changes committed and pushed" -ForegroundColor Green
    }
    catch {
        Write-Warning "  Failed to commit/push: $_"
        Write-Host "  Please commit and push manually." -ForegroundColor Yellow
    }
    finally {
        Pop-Location
    }
}

# --- Decryption Report ---
$reportDir = Join-Path $RepoDir ".migration-reports"
if (-not (Test-Path $reportDir)) { New-Item -ItemType Directory -Path $reportDir -Force | Out-Null }
$reportFile = Join-Path $reportDir "decryption-report-$(Get-Date -Format 'yyyyMMdd-HHmmss').csv"
$decryptionLog | Export-Csv -Path $reportFile -NoTypeInformation

# --- Summary ---
Write-Host "`n=== Decryption Summary ===" -ForegroundColor Cyan
Write-Host "Files processed:    $($filesToProcess.Count)" -ForegroundColor Gray
Write-Host "Secrets decrypted:  $totalDecrypted" -ForegroundColor $(if ($totalDecrypted -gt 0) { "Green" } else { "Yellow" })
Write-Host "Failures:           $totalFailed" -ForegroundColor $(if ($totalFailed -gt 0) { "Red" } else { "Green" })
Write-Host "Report saved:       $reportFile" -ForegroundColor Gray

if ($DryRun) {
    Write-Host "`n[DRY RUN] No files were modified. Re-run without -DryRun to apply changes." -ForegroundColor Yellow
}

if ($totalFailed -gt 0) {
    Write-Host "`n=== ACTION REQUIRED ===" -ForegroundColor Red
    Write-Host "Some secrets failed to decrypt. Check the report for details." -ForegroundColor Red
    Write-Host "This usually means the wrong passphrase was used." -ForegroundColor Red
    exit 1
}

Write-Host "`n=== NEXT STEPS ===" -ForegroundColor Cyan
Write-Host "1. Verify decrypted files match expected values" -ForegroundColor White
Write-Host "2. Run gitleaks scan to confirm secrets are back (expected)" -ForegroundColor White
Write-Host "3. Enable GitHub Advanced Security (push protection, secret scanning)" -ForegroundColor White
Write-Host "4. Rotate ALL credentials from the credential-rotation-checklist.csv" -ForegroundColor White
