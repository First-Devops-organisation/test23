<#
.SYNOPSIS
    Prepares the config.yml for reusable template migration by setting target repos.
.DESCRIPTION
    Takes the config.yml generated by 'gh actions-importer audit' and updates it
    with the correct target_url and ref for each reusable workflow and composite action.

    The config.yml is the KEY file for migrating ADO reusable templates to GitHub.
    It tells actions-importer which GitHub repository each converted template should go to.

    Usage flow:
    1. Run audit-pipelines.ps1 → generates output/pipeline-audit/config.yml
    2. Run this script → updates config.yml with target repos
    3. Run migrate-pipelines.ps1 with -ConfigFilePath → templates land in correct repos

.PARAMETER ConfigYml
    Path to the config.yml generated by actions-importer audit
.PARAMETER GitHubOrg
    GitHub organization name
.PARAMETER DefaultRepo
    Default repository for templates (if not using mapping)
.PARAMETER DefaultBranch
    Default branch (default: main)
.PARAMETER TemplateRepoMap
    Optional: comma-separated mapping of template-name=repo-name
    Example: "build-template.yml=shared-workflows,deploy-template.yml=deploy-actions"
.PARAMETER TemplateRepo
    Optional: single repo name for ALL templates (e.g. a shared .github or actions repo)
.PARAMETER OutputFile
    Path to write the updated config.yml (default: overwrites input)
.PARAMETER DryRun
    Show what would be changed without modifying the file
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$ConfigYml,

    [string]$GitHubOrg,

    [string]$DefaultRepo,

    [string]$DefaultBranch = "main",

    [string]$TemplateRepoMap,

    [string]$TemplateRepo,

    [string]$OutputFile,

    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

# --- Resolve parameters from env vars ---
$GitHubOrg = if ($GitHubOrg) { $GitHubOrg } elseif ($env:GH_ORG) { $env:GH_ORG } else { $null }

if (-not (Test-Path $ConfigYml)) {
    Write-Host "ERROR: Config file not found: $ConfigYml" -ForegroundColor Red
    Write-Host "`nGenerate it first by running:" -ForegroundColor Yellow
    Write-Host "  .\00-discovery\audit-pipelines.ps1 -AdoOrg `"YOUR_ORG`" -AdoProject `"YOUR_PROJECT`" -AdoPat `$env:ADO_PAT -GitHubPat `$env:GH_PAT" -ForegroundColor Gray
    Write-Host "`nThe audit output will contain config.yml in the output directory." -ForegroundColor Gray
    exit 1
}

if (-not $GitHubOrg) {
    Write-Host "ERROR: GitHub organization required. Use -GitHubOrg or set GH_ORG env var." -ForegroundColor Red
    exit 1
}

# --- Read the config.yml ---
$rawContent = Get-Content $ConfigYml -Raw
$lines = Get-Content $ConfigYml

Write-Host "=== Prepare Template Config ===" -ForegroundColor Cyan
Write-Host "  Config file: $ConfigYml" -ForegroundColor Gray
Write-Host "  GitHub org:  $GitHubOrg" -ForegroundColor Gray

# --- Parse template-to-repo mapping ---
$repoMap = @{}
if ($TemplateRepoMap) {
    foreach ($entry in $TemplateRepoMap.Split(',')) {
        $parts = $entry.Trim().Split('=', 2)
        if ($parts.Count -eq 2) {
            $repoMap[$parts[0].Trim()] = $parts[1].Trim()
        }
    }
    Write-Host "  Template-to-repo mappings: $($repoMap.Count)" -ForegroundColor Gray
}

# --- Determine default target repo ---
$defaultTargetRepo = $null
if ($TemplateRepo) {
    $defaultTargetRepo = $TemplateRepo
    Write-Host "  All templates → $GitHubOrg/$TemplateRepo" -ForegroundColor Green
} elseif ($DefaultRepo) {
    $defaultTargetRepo = $DefaultRepo
    Write-Host "  Default repo: $GitHubOrg/$DefaultRepo" -ForegroundColor Gray
}

if (-not $defaultTargetRepo -and $repoMap.Count -eq 0) {
    Write-Host "`nWARNING: No target repo specified. Templates need a target repository." -ForegroundColor Yellow
    Write-Host "  Options:" -ForegroundColor Yellow
    Write-Host "    -TemplateRepo `"shared-workflows`"              # Single repo for all templates" -ForegroundColor Gray
    Write-Host "    -DefaultRepo `"shared-workflows`"               # Default + per-template overrides" -ForegroundColor Gray
    Write-Host "    -TemplateRepoMap `"build.yml=repo1,deploy.yml=repo2`"  # Per-template mapping" -ForegroundColor Gray
    Write-Host "`n  Common pattern: Create a central '.github' or 'shared-workflows' repo." -ForegroundColor DarkGray
    exit 1
}

# --- Parse reusable workflows and composite actions from config ---
Write-Host "`n--- Current config.yml contents ---" -ForegroundColor White

$templates = @()
$currentSection = $null

foreach ($line in $lines) {
    if ($line -match '^reusable_workflows:') {
        $currentSection = "reusable_workflows"
        Write-Host "  [Reusable Workflows]" -ForegroundColor Cyan
    } elseif ($line -match '^composite_actions:') {
        $currentSection = "composite_actions"
        Write-Host "  [Composite Actions]" -ForegroundColor Cyan
    } elseif ($line -match '^\s+-\s+name:\s*(.+)') {
        $tplName = $matches[1].Trim()
        $templates += @{
            Name    = $tplName
            Section = $currentSection
        }
        Write-Host "    - $tplName" -ForegroundColor DarkGray
    } elseif ($line -match '^\s+target_url:\s*(.+)') {
        $url = $matches[1].Trim()
        Write-Host "      target_url: $url" -ForegroundColor DarkGray
    } elseif ($line -match '^\s+ref:\s*(.+)') {
        $ref = $matches[1].Trim()
        Write-Host "      ref: $ref" -ForegroundColor DarkGray
    }
}

Write-Host "`n  Total templates: $($templates.Count)" -ForegroundColor White

# --- Build updated config ---
Write-Host "`n--- Updated config ---" -ForegroundColor Green

$updatedLines = @()
$currentSection = $null
$lastTemplateName = $null

foreach ($line in $lines) {
    if ($line -match '^reusable_workflows:' -or $line -match '^composite_actions:' -or $line -match '^source_files:') {
        $currentSection = $line.Trim().TrimEnd(':')
        $updatedLines += $line
        continue
    }

    if ($line -match '^\s+-\s+name:\s*(.+)') {
        $lastTemplateName = $matches[1].Trim()
        $updatedLines += $line

        # Determine target repo for this template
        $targetRepo = $null
        if ($repoMap.ContainsKey($lastTemplateName)) {
            $targetRepo = $repoMap[$lastTemplateName]
        } elseif ($defaultTargetRepo) {
            $targetRepo = $defaultTargetRepo
        }

        if ($targetRepo) {
            $targetUrl = "https://github.com/$GitHubOrg/$targetRepo"
            $updatedLines += "    target_url: $targetUrl"
            $updatedLines += "    ref: $DefaultBranch"
            Write-Host "  $lastTemplateName → $targetUrl ($DefaultBranch)" -ForegroundColor Green
        } else {
            Write-Host "  $lastTemplateName → (no target set, skipped)" -ForegroundColor Yellow
        }
        continue
    }

    # Skip existing target_url and ref lines (we're replacing them)
    if ($line -match '^\s+target_url:' -or $line -match '^\s+ref:') {
        continue
    }

    $updatedLines += $line
}

$updatedContent = $updatedLines -join "`n"

# --- Show the result ---
Write-Host "`n--- Generated config.yml ---" -ForegroundColor Cyan
Write-Host $updatedContent -ForegroundColor DarkGray
Write-Host "--- end ---" -ForegroundColor Cyan

if ($DryRun) {
    Write-Host "`n  [DRY RUN] No changes written." -ForegroundColor Yellow
} else {
    $outPath = if ($OutputFile) { $OutputFile } else { $ConfigYml }
    $updatedContent | Out-File -FilePath $outPath -Encoding utf8
    Write-Host "`n  Config written to: $outPath" -ForegroundColor Green
}

# --- Print next steps ---
Write-Host "`n=== Next Steps ===" -ForegroundColor Cyan
$configPath = if ($OutputFile) { $OutputFile } else { $ConfigYml }
Write-Host @"

1. REVIEW the updated config.yml to verify target repos are correct

2. DRY-RUN with templates routed to correct repos:
   .\02-migrate\migrate-pipelines.ps1 ``
       -AdoProject "YOUR_PROJECT" ``
       -PipelineId YOUR_ID ``
       -Mode "dry-run" ``
       -ConfigFilePath "$configPath"

3. MIGRATE — create PRs in each target repo:
   .\02-migrate\migrate-pipelines.ps1 ``
       -AdoProject "YOUR_PROJECT" ``
       -PipelineId YOUR_ID ``
       -Mode "migrate" ``
       -ConfigFilePath "$configPath"

   This will open a PR for:
   - The main pipeline workflow in the pipeline's target repo
   - Each reusable workflow in its specified target repo
   - Each composite action in its specified target repo

4. REVIEW & MERGE the PRs in GitHub
"@ -ForegroundColor Gray
