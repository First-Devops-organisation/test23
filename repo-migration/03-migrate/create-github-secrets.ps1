<#
.SYNOPSIS
    Creates GitHub repository secrets from secret-values.json produced by scrub-secrets.ps1.
.DESCRIPTION
    After migration, reads the saved secret values and creates corresponding
    GitHub repository-level secrets using the gh CLI.

    Features:
      - Validates secret names (alphanumeric + underscore, no leading digit)
      - Validates secret values are not empty
      - Retry logic with exponential backoff (default 3 retries)
      - Rate-limit friendly (500ms delay between API calls)
      - Partial success handling (only hard-fails if ALL secrets fail)

    Requires: gh CLI authenticated with repo scope
.PARAMETER SecretValuesFile
    Path to secret-values.json (generated by 02-prep/scrub-secrets.ps1)
.PARAMETER MaxRetries
    Maximum retry attempts per secret (default: 3)
.PARAMETER DeleteAfterCreate
    If set, deletes secret-values.json after processing (default: false for pipeline run, handled in cleanup)
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$SecretValuesFile,

    [int]$MaxRetries = 3,

    [bool]$DeleteAfterCreate = $false
)

$ErrorActionPreference = "Continue"

# --- Validate GH_TOKEN ---
$ghPat = $env:GH_PAT
if ([string]::IsNullOrWhiteSpace($ghPat)) {
    $ghPat = $env:GH_TOKEN
}
if ([string]::IsNullOrWhiteSpace($ghPat)) {
    Write-Error "Set GH_PAT or GH_TOKEN environment variable"
    exit 1
}
$env:GH_TOKEN = $ghPat

# --- Load secrets ---
if (-not (Test-Path $SecretValuesFile)) {
    Write-Host "No secret-values.json found — no secrets to create." -ForegroundColor Green
    exit 0
}

$secrets = Get-Content $SecretValuesFile -Raw | ConvertFrom-Json
if ($secrets.Count -eq 0) {
    Write-Host "No secrets in secret-values.json — all repos were clean." -ForegroundColor Green
    exit 0
}

Write-Host "=== Creating GitHub Secrets ===" -ForegroundColor Cyan
Write-Host "Total secrets to create: $($secrets.Count)" -ForegroundColor Yellow

$created = 0
$failed = 0
$failedSecrets = @()

foreach ($entry in $secrets) {
    Write-Host "`n  Repo: $($entry.GitHubRepo)" -ForegroundColor Yellow
    Write-Host "    Secret: $($entry.SecretName) ($($entry.RuleID))" -ForegroundColor Gray

    # Validate secret name (GitHub requires alphanumeric + underscore, no leading digit)
    if ($entry.SecretName -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') {
        Write-Host "    ✗ Skipped: Invalid secret name '$($entry.SecretName)' (must be alphanumeric + underscore, no leading digit)" -ForegroundColor Red
        $failedSecrets += [PSCustomObject]@{
            SecretName = $entry.SecretName
            Repo       = $entry.GitHubRepo
            Error      = "Invalid secret name format"
        }
        $failed++
        continue
    }

    # Validate secret value is not empty
    if ([string]::IsNullOrWhiteSpace($entry.SecretValue)) {
        Write-Host "    ✗ Skipped: Empty secret value for '$($entry.SecretName)'" -ForegroundColor Red
        $failedSecrets += [PSCustomObject]@{
            SecretName = $entry.SecretName
            Repo       = $entry.GitHubRepo
            Error      = "Empty secret value"
        }
        $failed++
        continue
    }

    $success = $false
    for ($attempt = 1; $attempt -le $MaxRetries; $attempt++) {
        try {
            $entry.SecretValue | gh secret set $entry.SecretName --repo $entry.GitHubRepo 2>&1
            if ($LASTEXITCODE -eq 0) {
                Write-Host "    ✓ Created: $($entry.SecretName)" -ForegroundColor Green
                $created++
                $success = $true
                break
            } else {
                Write-Host "    ⚠ Attempt $attempt/$MaxRetries failed (exit code: $LASTEXITCODE)" -ForegroundColor Yellow
            }
        }
        catch {
            Write-Host "    ⚠ Attempt $attempt/$MaxRetries error: $_" -ForegroundColor Yellow
        }

        if ($attempt -lt $MaxRetries) {
            $delay = [math]::Pow(2, $attempt)
            Write-Host "    Retrying in ${delay}s..." -ForegroundColor Gray
            Start-Sleep -Seconds $delay
        }
    }

    if (-not $success) {
        Write-Host "    ✗ Failed after $MaxRetries attempts: $($entry.SecretName)" -ForegroundColor Red
        $failedSecrets += [PSCustomObject]@{
            SecretName = $entry.SecretName
            Repo       = $entry.GitHubRepo
            Error      = "Failed after $MaxRetries retries"
        }
        $failed++
    }

    # Small delay between API calls to avoid rate limiting
    Start-Sleep -Milliseconds 500
}

Write-Host "`n=== GitHub Secrets Summary ===" -ForegroundColor Cyan
Write-Host "Created: $created" -ForegroundColor Green
Write-Host "Failed:  $failed" -ForegroundColor $(if ($failed -gt 0) { "Yellow" } else { "Green" })

if ($failedSecrets.Count -gt 0) {
    Write-Host "`n=== Failed Secrets Detail ===" -ForegroundColor Yellow
    foreach ($fs in $failedSecrets) {
        Write-Host "  ✗ $($fs.SecretName) @ $($fs.Repo) — $($fs.Error)" -ForegroundColor Red
    }
    Write-Host ""
}

# Delete the secret-values.json for security
if ($DeleteAfterCreate -and (Test-Path $SecretValuesFile)) {
    Remove-Item $SecretValuesFile -Force
    Write-Host "Deleted secret-values.json for security." -ForegroundColor Gray
}

# Only hard-fail if ALL secrets failed; partial success = warning
if ($created -eq 0 -and $failed -gt 0) {
    Write-Error "All $failed secrets failed to create. Pipeline cannot continue."
    exit 1
} elseif ($failed -gt 0) {
    Write-Host "`n##vso[task.logissue type=warning]$failed out of $($created + $failed) secrets failed to create. Review the failed secrets above." -ForegroundColor Yellow
    Write-Host "##vso[task.complete result=SucceededWithIssues;]$failed secrets failed"
}

Write-Host "`n=== Done ===" -ForegroundColor Green
Write-Host "Next step: Verify secrets in GitHub repo Settings → Secrets." -ForegroundColor Gray
